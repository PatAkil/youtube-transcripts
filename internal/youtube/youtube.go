// Package youtube is the single seam through which the CLI reaches YouTube.
// It exposes a Client interface, a key-free HTTP implementation and a
// map-backed Fake for tests.
package youtube

import (
	"context"
	"time"
)

// Cue is one line of a Transcript: the moment it starts and the words spoken.
type Cue struct {
	Start time.Duration
	Text  string
}

// VideoMeta is the metadata the CLI stores next to a Transcript.
type VideoMeta struct {
	VideoID     string
	ChannelID   string
	ChannelName string
	Title       string
	Published   time.Time
}

// TrackKind says where a Transcript came from.
type TrackKind string

const (
	// TrackManual is a track uploaded by the Channel.
	TrackManual TrackKind = "manual"
	// TrackAuto is a track generated by YouTube's speech recognition.
	TrackAuto TrackKind = "auto"
	// TrackNone means the Video has no English track.
	TrackNone TrackKind = ""
)

// Transcript is the English track of a Video as structured cues, together with
// the Video's metadata. Track == TrackNone means the Video has no English
// track; Meta is still filled in and Cues is empty.
type Transcript struct {
	Meta  VideoMeta
	Track TrackKind
	Cues  []Cue
}

// Client is the YouTube seam. Both methods are key-free.
type Client interface {
	ListNewestVideos(ctx context.Context, channelID string) ([]VideoMeta, error)
	FetchTranscript(ctx context.Context, videoID string) (Transcript, error)
}
